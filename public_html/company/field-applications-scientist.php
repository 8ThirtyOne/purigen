                            <em>DESCRIPTION</em></br>
                            Purigen Biosystems, headquartered in Pleasanton CA, is redefining nucleic acid sample preparation with the Ionic&reg; Purification System. This innovative platform is based on the highly efficient isotachophoresis technology invented by Juan Santiago, PhD, and his team at Stanford University. The Ionic system, comprised of an automated benchtop instrument, microfluidic chips and reagent kits, purifies nucleic acids from a wide variety of sample types, including minute or otherwise challenging cancer samples. The purified nucleic acids are then immediately compatible with a wide range of downstream detection methods, including next-generation sequencing (NGS), PCR and other genomic tests.
                            </br></br>
                            
